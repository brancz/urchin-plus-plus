#!/usr/bin/env python3
"""Turn the original Urchin's footprints into atopile atomic parts (CLAUDE.md rule 1).

    "$KICAD_PY" scripts/geometry/mechanical_parts.py [--parts-dir hardware/parts]

atopile deletes every footprint it doesn't own, so the key positions, the
tenting puck and the case holes are atopile parts too. Their footprints are the
original's, unchanged except for the format upgrade KiCad's writer applies:
  KEY_CHOC     SW_Hotswap_Kailh_Choc_V1_tweaked (reference/urchin/lib): switch holes
               plus the Kailh Choc hotswap socket pads 1/2 on B.Cu. The socket isn't
               stocked at JLC or LCSC (ARCHITECTURE.md decision log), so it is
               hand-soldered: the footprint is excluded from the BOM and position
               files and its socket pads carry no paste (no stencil aperture).
  PUCK         Tenting_Puck2_no_pads (reference/urchin/lib), unchanged
  HOLE_M2_4_2  swoop:M2_hole_4.2mm   (embedded in reference/urchin/main.kicad_pcb)
  HOLE_M2_3_5  swoop:M2_hole_3.5mm / chocolad:M2_hole_3.5mm (identical pads)
               Case holes are made non-plated, same drill: several sit 0.25 mm from
               the board edge, and plating them serves no purpose (no net).
UUIDs are derived from the part name and item index, so reruns reproduce the
committed files byte for byte (CI checks that against a fresh copy of the original).
Two cosmetic changes keep atopile from mangling them (it matches footprint items
by geometry only and drops what it doesn't model, reports/phase0/): of two items
with identical geometry on different layers only one is kept (courtyard over fab;
the puck, which mounts underneath, keeps its bottom silkscreen), and texts are
dropped where they only repeat the designator (atopile strips those). Holes and pads are untouched.
None has an LCSC number; each instance needs an explicit has_designator.
Runs under KiCad's Python (pcbnew); Python 3.9.
"""

import argparse
import os
import re
import uuid
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "reference/urchin"
SYMBOL = '''(kicad_symbol_lib
	(version 20241209)
	(generator "urchin++")
	(symbol "{name}"
		(in_bom no)
		(on_board yes)
		(property "Reference" "{prefix}" (at 0 2.54 0) (effects (font (size 1.27 1.27))))
		(property "Value" "{name}" (at 0 -2.54 0) (effects (font (size 1.27 1.27))))
		(property "Footprint" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
		(property "Datasheet" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
		(property "Description" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
		(symbol "{name}_0_1"
			(rectangle (start -2.54 1.27) (end 2.54 -1.27) (stroke (width 0.254) (type default)) (fill (type none)))
		)
{pins}	)
)
'''
PIN = '''		(symbol "{name}_1_1"
			(pin passive line (at -5.08 0 0) (length 2.54) (name "{a}" (effects (font (size 1.27 1.27)))) (number "{a}" (effects (font (size 1.27 1.27)))))
			(pin passive line (at 5.08 0 180) (length 2.54) (name "{b}" (effects (font (size 1.27 1.27)))) (number "{b}" (effects (font (size 1.27 1.27)))))
		)
'''
ATO = '''#pragma experiment("TRAITS")
import is_atomic_part
import has_designator_prefix

component {name}_package:
    """{doc} Generated by scripts/geometry/mechanical_parts.py; not in the JLC BOM."""
    trait is_atomic_part<manufacturer="none", partnumber="{name}", footprint="{fp}.kicad_mod", symbol="{name}.kicad_sym">
    trait has_designator_prefix<prefix="{prefix}">
{pins}'''


def from_library(lib_dir, name):
    fp = pcbnew.PCB_IO_KICAD_SEXPR().FootprintLoad(str(lib_dir), name)
    if fp is None:
        sys.exit("no %s in %s" % (name, lib_dir))
    return pcbnew.FOOTPRINT(fp)  # own copy: the reader's cache owns the original


def from_board(board, lib_id):
    for f in board.GetFootprints():
        if f.GetFPIDAsString() == lib_id:
            fp = pcbnew.FOOTPRINT(f)  # copy
            if fp.GetLayer() != pcbnew.F_Cu:
                fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
            fp.SetPosition(pcbnew.VECTOR2I(0, 0))
            fp.SetOrientationDegrees(0)
            for p in fp.Pads():
                p.SetNetCode(0)
            return fp
    sys.exit("no footprint %s on the reference board" % lib_id)


def identity(g):
    """atopile's PCB_Transformer.identify_obj for a footprint graphic (2-decimal mm)."""
    r = lambda v: round(pcbnew.ToMM(v), 2)
    if g.GetClass() == "PCB_TEXT":
        return ("text", r(g.GetFPRelativePosition().x), r(g.GetFPRelativePosition().y))
    s = g.Cast()
    shape = s.GetShapeStr()
    loc = lambda p: (r(p.x), r(p.y))
    fp = s.GetParentFootprint()
    rel = lambda p: loc(p - fp.GetPosition())
    if shape == "Arc":
        return (shape, rel(s.GetStart()), rel(s.GetArcMid()), rel(s.GetEnd()))
    if shape == "Polygon":
        poly = s.GetPolyShape().Outline(0)
        return (shape, tuple(rel(poly.CPoint(i)) for i in range(poly.PointCount())))
    if shape == "Circle":
        return (shape, rel(s.GetCenter()), rel(s.GetEnd()))
    return (shape, rel(s.GetStart()), rel(s.GetEnd()))


def sanitize(fp, prefer):
    """Drop geometric duplicates (keeping the layer earliest in `prefer`), lock texts."""
    groups = {}
    for g in list(fp.GraphicalItems()):
        groups.setdefault(identity(g), []).append(g)
    for items in groups.values():
        if len(items) < 2:
            continue
        rank = lambda g: prefer.index(g.GetLayerName()) if g.GetLayerName() in prefer else len(prefer)
        items.sort(key=rank)
        for g in items[1:]:
            fp.Remove(g)
    for g in list(fp.GraphicalItems()):
        if g.GetClass() == "PCB_TEXT" and g.GetText() in ("${REFERENCE}", "%R"):
            fp.Remove(g)  # atopile strips these duplicate designators anyway


def write_part(parts_dir, name, fp, prefix, doc, pins=None, exclude=True, prefer=()):
    out = parts_dir / name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    fp_name = fp.GetFPIDAsString().split(":")[-1]  # GetFPID() comes back unwrapped on later calls
    if exclude:
        fp.SetExcludedFromBOM(True)
        fp.SetExcludedFromPosFiles(True)
    fp.SetReference(prefix + "**")
    board = pcbnew.BOARD()
    board.Add(fp)  # GetParentFootprint/Remove need a footprint on a board
    sanitize(fp, list(prefer) + ["F.Courtyard", "B.Courtyard", "F.Silkscreen", "B.Silkscreen", "F.Fab", "B.Fab"])
    tmp = tempfile.mkdtemp()
    lib = os.path.join(tmp, "lib.pretty")
    os.mkdir(lib)
    pcbnew.PCB_IO_KICAD_SEXPR().FootprintSave(lib, fp)
    text = open(os.path.join(lib, fp_name + ".kicad_mod"), encoding="utf-8").read()
    counter = iter(range(10 ** 6))
    text = re.sub(r'\(uuid "[0-9a-f-]+"\)',
                  lambda m: '(uuid "%s")' % uuid.uuid5(uuid.NAMESPACE_URL, "urchin++/%s/%d" % (name, next(counter))), text)
    (out / (fp_name + ".kicad_mod")).write_text(text, encoding="utf-8")
    pin_sym = PIN.format(name=name, a=pins[0], b=pins[1]) if pins else ""
    (out / (name + ".kicad_sym")).write_text(SYMBOL.format(name=name, prefix=prefix, pins=pin_sym))
    pin_ato = "\n" + "".join("    pin %s\n" % p for p in pins) if pins else ""
    (out / (name + ".ato")).write_text(ATO.format(name=name, fp=fp_name, prefix=prefix, doc=doc, pins=pin_ato))
    print("%-12s <- %s" % (name, fp_name))


PARTS = {
    "KEY_CHOC": dict(src=("lib", "SW_Hotswap_Kailh_Choc_V1_tweaked"), prefix="SW", pins=("1", "2"), no_paste=True,
                     doc="Kailh Choc v1 switch position with a hand-soldered Kailh hotswap socket (CPG135001S30)."),
    "PUCK": dict(src=("lib", "Tenting_Puck2_no_pads"), prefix="H", prefer=("B.Silkscreen",),
                 doc="Tenting-puck mount of the original Urchin."),
    "HOLE_M2_4_2": dict(src=("board", "swoop:M2_hole_4.2mm"), prefix="H", npth=True,
                        doc="Case mounting hole, 3.8 mm drill (non-plated; the original has a 4.2 mm pad)."),
    "HOLE_M2_3_5": dict(src=("board", "swoop:M2_hole_3.5mm"), same_as="chocolad:M2_hole_3.5mm", prefix="H", npth=True,
                        doc="Case mounting hole, 2.2 mm drill (non-plated; the original has a 3.5 mm pad)."),
}


def one(parts, name):
    spec = PARTS[name]
    kind, ident = spec["src"]
    if kind == "lib":
        fp = from_library(REF / "lib", ident)
    else:
        board = pcbnew.LoadBoard(str(REF / "main.kicad_pcb"))
        fp = from_board(board, ident)
        if spec.get("same_as"):
            other = from_board(board, spec["same_as"])
            sig = lambda f: sorted((p.GetPosition().x, p.GetPosition().y, p.GetDrillSize().x, p.GetSize(pcbnew.F_Cu).x)
                                   for p in f.Pads())
            if sig(fp) != sig(other):
                sys.exit("%s and %s pads differ; they need separate parts" % (ident, spec["same_as"]))
    for p in fp.Pads():
        if spec.get("npth") and p.GetDrillSize().x > 0:
            p.SetAttribute(pcbnew.PAD_ATTRIB_NPTH)
            p.SetSize(pcbnew.F_Cu, p.GetDrillSize())
            p.SetLayerSet(pcbnew.LSET.AllCuMask().AddLayer(pcbnew.F_Mask).AddLayer(pcbnew.B_Mask))
        if spec.get("no_paste") and p.GetAttribute() == pcbnew.PAD_ATTRIB_SMD:
            p.SetLayerSet(p.GetLayerSet().RemoveLayer(pcbnew.F_Paste).RemoveLayer(pcbnew.B_Paste))
    write_part(parts, name, fp, spec["prefix"], spec["doc"], pins=spec.get("pins"), prefer=spec.get("prefer", ()))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--parts-dir", default=str(ROOT / "hardware/parts"))
    ap.add_argument("--one", help=argparse.SUPPRESS)
    args = ap.parse_args()
    if args.one:
        one(Path(args.parts_dir), args.one)
        sys.stdout.flush()
        os._exit(0)  # skip destructors: the footprint is owned by both Python and its board (segfaults)
    # One process per part: KiCad 9's SWIG types come back unwrapped after the first
    # footprint has been through a temporary board.
    for name in PARTS:
        subprocess.run([sys.executable, __file__, "--parts-dir", args.parts_dir, "--one", name], check=True)


if __name__ == "__main__":
    main()
