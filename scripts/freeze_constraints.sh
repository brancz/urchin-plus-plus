#!/usr/bin/env bash
# Freeze the Python dependency trees of atopile and KiKit from this machine (CLAUDE.md rule 4).
#
#   scripts/freeze_constraints.sh            # rewrite constraints/atopile.txt and constraints/kikit.txt
#   scripts/freeze_constraints.sh --check    # exit 1 if the installed trees differ from the files
#
# atopile and KiKit pin few of their dependencies, so a fresh install drifts. CI and
# docs/SETUP.md install both with these files as constraints. Rerun after any
# deliberate toolchain change and commit the result.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
: "${KICAD_PY:?set KICAD_PY to the KiCad bundled Python}"
ATO_PY="$(uv tool dir)/atopile/bin/python"

atopile_tree() { uv pip freeze --python "$ATO_PY" | LC_ALL=C sort -f; }
kikit_tree() {
  "$KICAD_PY" - <<'EOF'
import importlib.metadata as md
import re

def name(req):
    return re.split(r"[\s;<>=!~\[(]", req, maxsplit=1)[0].lower()

seen, todo = {}, ["kikit"]
while todo:
    n = todo.pop()
    if n in seen:
        continue
    try:
        dist = md.distribution(n)
    except md.PackageNotFoundError:
        continue  # optional or platform-specific dependency that isn't installed
    seen[n] = "%s==%s" % (dist.metadata["Name"], dist.version)
    todo += [name(r) for r in (dist.requires or []) if "extra ==" not in r]
for line in sorted(seen.values(), key=str.lower):
    print(line)
EOF
}

header() { printf '# Generated by scripts/freeze_constraints.sh from %s. Do not edit.\n' "$1"; }

if [ "${1:-}" = "--check" ]; then
  status=0
  diff <(header "the atopile uv tool env"; atopile_tree) "$ROOT/constraints/atopile.txt" >/dev/null \
    || { echo "constraints/atopile.txt differs from the installed atopile environment"; status=1; }
  diff <(header "KiCad's Python (KiKit and its dependencies)"; kikit_tree 2>/dev/null) "$ROOT/constraints/kikit.txt" >/dev/null \
    || { echo "constraints/kikit.txt differs from KiKit's installed dependencies"; status=1; }
  exit "$status"
fi

mkdir -p "$ROOT/constraints"
{ header "the atopile uv tool env"; atopile_tree; } >"$ROOT/constraints/atopile.txt"
{ header "KiCad's Python (KiKit and its dependencies)"; kikit_tree 2>/dev/null; } >"$ROOT/constraints/kikit.txt"
wc -l "$ROOT/constraints/"*.txt
