#!/usr/bin/env python3
"""Generate the ZMK board's pin and layout devicetree from the hardware sources (phase 8).

    python3 scripts/firmware/gen_board.py [--check]

The LED outputs are open-drain: they only ever pull a cathode low. Each half's LED pins
are key inputs on the other half, so a half flashed with the other half's image must not
drive them high against a pressed key's short to ground.

Writes, into firmware/boards/urchin_pp/:
  urchin_pp_left-pins.dtsi, urchin_pp_right-pins.dtsi
      each half's direct-wired key GPIOs (kscan input order r0c0..r0c4, r1c0..r1c4,
      r2c0..r2c4, t0, t1), its status LED's red/green/blue GPIOs and the charger's
      PGOOD/CHG sense GPIOs, from hardware/pinmap.json (scripts/circuit/gen_halves.py).
  urchin_pp-layouts.dtsi
      the matrix transform (34 keymap positions; the right half's kscan columns are
      offset by 17) and ZMK's physical layout for ZMK Studio, with every key at its
      switch position and rotation from hardware/geometry/urchin.json (rule 1's source).

Keymap positions: three rows of 5 + 5 keys, then the thumbs. Row by row, left half
c0 (outer pinky) to c4 (index), right half c4 (index) to c0 (outer pinky); thumbs left
t0, left t1 (inner), right t1 (inner), right t0. The right half's signals are mirrored
names (gen_halves.py), so its c0 is its outer pinky column.

Layout units: 1 key unit = 18 mm, the Urchin's column pitch; rows are 17 mm apart, so
keys are 100 x 94 centi-units. ZMK's rotation is clockwise-positive, KiCad's
counter-clockwise-positive. Each half must use every key and function exactly once, no
GPIO twice, and not P0.18 (reset) or P0.09/P0.10 (NFC). --check fails if any generated
file differs. Python 3.9.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BOARD_DIR = ROOT / "firmware/boards/urchin_pp"
KEY_ORDER = ["r%dc%d" % (r, c) for r in range(3) for c in range(5)] + ["t0", "t1"]
HALF_KEYS = len(KEY_ORDER)  # 17: the right half's kscan columns are offset by this
UNIT_MM = 18.0
KEY_W, KEY_H = 100, 94
GAP_UNITS = 150  # between the halves in the physical layout
HEADER = "/* Generated by scripts/firmware/gen_board.py from %s. Do not edit. */\n"


def gpio(name):
    """'P0_17' -> ('gpio0', 17)"""
    port, pin = name[1:].split("_")
    return "gpio%d" % int(port), int(pin)


def keymap_positions():
    """[(half, signal)] in keymap order."""
    out = []
    for r in range(3):
        out += [("left", "r%dc%d" % (r, c)) for c in range(5)]
        out += [("right", "r%dc%d" % (r, c)) for c in reversed(range(5))]
    return out + [("left", "t0"), ("left", "t1"), ("right", "t1"), ("right", "t0")]


RESERVED = {"P0_18": "reset", "P0_09": "NFC1", "P0_10": "NFC2"}
FUNCTIONS = ("led_r", "led_g", "led_b", "pgood_sense", "chg_sense")


def validate(half, rows):
    """Every key and function exactly once, no GPIO twice, no reserved pin."""
    signals = [r["signal"] for r in rows]
    missing = sorted((set(KEY_ORDER) | set(FUNCTIONS)) - set(signals))
    dupes = sorted({g for g in (r["gpio"] for r in rows) if [x["gpio"] for x in rows].count(g) > 1})
    reserved = sorted("%s (%s)" % (r["gpio"], RESERVED[r["gpio"]]) for r in rows if r["gpio"] in RESERVED)
    problems = (["missing %s" % ", ".join(missing)] if missing else []) + \
               (["GPIO used twice: %s" % ", ".join(dupes)] if dupes else []) + \
               (["reserved pin used: %s" % ", ".join(reserved)] if reserved else [])
    if problems:
        sys.exit("gen_board: %s half: %s" % (half, "; ".join(problems)))


def pins_dtsi(half, rows):
    validate(half, rows)
    by_signal = {r["signal"]: r for r in rows}
    lines = [HEADER % "hardware/pinmap.json", "&kscan0 {", "    input-gpios"]
    for i, sig in enumerate(KEY_ORDER):
        r = by_signal[sig]
        port, pin = gpio(r["gpio"])
        lines.append("        %s <&%s %d (GPIO_ACTIVE_LOW | GPIO_PULL_UP)>  /* %d: %s %s, module pin %d */" % (
            "=" if i == 0 else ",", port, pin, i, sig, r["ref"], r["module_pin"]))
    lines += ["        ;", "};", ""]
    for label, sig in (("led_red", "led_r"), ("led_green", "led_g"), ("led_blue", "led_b")):
        port, pin = gpio(by_signal[sig]["gpio"])
        lines.append("&%s { gpios = <&%s %d (GPIO_ACTIVE_LOW | GPIO_OPEN_DRAIN)>; };  /* status LED cathode, module pin %d */" % (
            label, port, pin, by_signal[sig]["module_pin"]))
    lines += ["", "&battery {"]
    for prop, sig in (("power-good-gpios", "pgood_sense"), ("charging-gpios", "chg_sense")):
        port, pin = gpio(by_signal[sig]["gpio"])
        lines.append("    %s = <&%s %d (GPIO_ACTIVE_LOW | GPIO_PULL_UP)>;  /* %s, module pin %d */" % (
            prop, port, pin, sig, by_signal[sig]["module_pin"]))
    lines.append("};")
    if half == "right":
        lines += ["", "&default_transform {", "    col-offset = <%d>;" % HALF_KEYS, "};"]
    return "\n".join(lines) + "\n"


def layouts_dtsi(pinmap, geometry):
    refs = {half: {r["signal"]: r["ref"] for r in rows if r["kind"] == "key"} for half, rows in pinmap.items()}
    switches = {half: {s["ref"]: s for s in geometry[half]["switches"]} for half in pinmap}
    # place the left half first, then the right half to its right (KiCad has them the other way round)
    xs = {half: [switches[half][ref]["x"] for ref in refs[half].values()] for half in pinmap}
    ys = [switches[h][ref]["y"] for h in pinmap for ref in refs[h].values()]
    left_w = (max(xs["left"]) - min(xs["left"])) / UNIT_MM * 100
    origin = {"left": min(xs["left"]), "right": min(xs["right"])}
    offset = {"left": KEY_W / 2, "right": KEY_W / 2 + left_w + GAP_UNITS}
    y0 = min(ys)

    transform, keys = [], []
    for half, sig in keymap_positions():
        col = KEY_ORDER.index(sig) + (HALF_KEYS if half == "right" else 0)
        transform.append("RC(0,%d)" % col)
        sw = switches[half][refs[half][sig]]
        cx = offset[half] + (sw["x"] - origin[half]) / UNIT_MM * 100
        cy = KEY_H / 2 + (sw["y"] - y0) / UNIT_MM * 100
        rot = int(round(-sw["rot"] * 100))  # ZMK: clockwise-positive centi-degrees
        keys.append((KEY_W, KEY_H, int(round(cx - KEY_W / 2)), int(round(cy - KEY_H / 2)), rot,
                     int(round(cx)), int(round(cy)), half, sig, sw["ref"]))
    num = lambda v: "(%d)" % v if v < 0 else "%d" % v
    lines = [HEADER % "hardware/pinmap.json and hardware/geometry/urchin.json",
             "#include <physical_layouts.dtsi>", "", "/ {",
             "    default_transform: keymap_transform_0 {",
             "        compatible = \"zmk,matrix-transform\";",
             "        rows = <1>;",
             "        columns = <%d>;" % (2 * HALF_KEYS),
             "        map = <"]
    for i in range(0, 30, 10):
        lines.append("            " + " ".join(transform[i:i + 10]))
    lines += ["            " + " ".join(transform[30:]), "        >;", "    };", "",
              "    physical_layout0: physical_layout_0 {",
              "        compatible = \"zmk,physical-layout\";",
              "        display-name = \"urchin++\";",
              "        transform = <&default_transform>;",
              "        keys  //                     w   h     x    y      rot    rx    ry"]
    for i, (w, h, x, y, r, rx, ry, half, sig, ref) in enumerate(keys):
        lines.append("            %s <&key_physical_attrs %3d %3d %5d %4d %8s %5d %5d>  /* %d: %s %s %s */" % (
            "=" if i == 0 else ",", w, h, x, y, num(r), rx, ry, i, half, sig, ref))
    lines += ["            ;", "    };", "};"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    pinmap = json.loads((ROOT / "hardware/pinmap.json").read_text())["halves"]
    geometry = json.loads((ROOT / "hardware/geometry/urchin.json").read_text())["halves"]
    files = {"urchin_pp_%s-pins.dtsi" % half: pins_dtsi(half, rows) for half, rows in pinmap.items()}
    files["urchin_pp-layouts.dtsi"] = layouts_dtsi(pinmap, geometry)
    stale = []
    for name, text in sorted(files.items()):
        path = BOARD_DIR / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check:
        print("gen_board: %s" % ("OK" if not stale else "FAIL, stale: " + ", ".join(stale)))
        sys.exit(1 if stale else 0)
    print("gen_board: wrote %s" % ", ".join(sorted(files)))


if __name__ == "__main__":
    main()
